#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pattern_as_vice() {
        let p = ram_pattern();
        // Seen in VICE (-raminitrandomchance 0): $00 $00 $FF $FF $FF $FF $00...
        assert_eq!(p[..10], [0, 0, 0xFF, 0xFF, 0xFF, 0xFF, 0, 0, 0, 0]);
        // Inverted in the second 16 KB: at $C300 $FF $FF $00 $00 $00 $00 $FF
        assert_eq!(p[0x4000..0x4003], [0xFF, 0xFF, 0]);
        assert_eq!(p[0xC300..0xC307], [0xFF, 0xFF, 0, 0, 0, 0, 0xFF]);
        assert_eq!(COLOR_RAM[..4], [0x4, 0xF, 0x1, 0xB]);
    }

    #[test]
    fn random_bits_about_one_in_a_thousand() {
        let flipped: u32 = ram().iter().zip(ram_pattern().iter()).map(|(a, b)| (a ^ b).count_ones()).sum();
        assert!((350..750).contains(&flipped), "{flipped} bits flipped out of 524288");
        // Always the same: the generator starts from a fixed state
        assert_eq!(ram()[..], ram()[..]);
    }
}
