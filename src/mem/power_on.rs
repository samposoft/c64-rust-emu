//! Memory contents at power-on, as in VICE. The dynamic RAM does not start
//! empty: every cell settles to 0 or 1 according to the chip's layout, so
//! the C64 finds blocks of $00 and $FF bytes, with a few random bits. The
//! pattern is VICE's default for the C64 (ram.c): four bytes of $00 and
//! four of $FF, shifted by two bytes, inverted every 16 KB, and one bit in
//! a thousand flipped at random (with VICE's generator from a fixed state,
//! see `random`). The color RAM holds the values read on a real C64
//! (vicii-colorram.h). A reset does not change them: only switching the
//! machine on.

use crate::random::Pcg;

/// Chance of a flipped bit, in ten thousandths (VICE's
/// RAMInitRandomChance, 0.1%).
const RANDOM_CHANCE: f64 = 10.0 / 10_000.0;

/// The pattern without the random bits (VICE with
/// `-raminitrandomchance 0`).
pub fn ram_pattern() -> Box<[u8; 0x10000]> {
    let mut ram = Box::new([0u8; 0x10000]);
    for (offset, b) in ram.iter_mut().enumerate() {
        // RAMInitValueOffset 2, RAMInitValueInvert 4, RAMInitStartValue 0
        let value = if ((offset + 2) / 4) & 1 != 0 { 0xFF } else { 0x00 };
        // RAMInitPatternInvert 16384 with RAMInitPatternInvertValue $FF
        *b = value ^ if (offset / 16384) & 1 != 0 { 0xFF } else { 0x00 };
    }
    ram
}

/// RAM at power-on: the pattern with the random bits, flipped as in
/// VICE's ram_init_with_pattern (the gaps between two flipped bits are
/// drawn from the geometric distribution).
pub fn ram() -> Box<[u8; 0x10000]> {
    let mut ram = ram_pattern();
    let mut rng = Pcg::new();
    let log_1mp = (-RANDOM_CHANCE).ln_1p();
    let gap = |rng: &mut Pcg| ((-rng.unit()).ln_1p() / log_1mp).floor().min(u32::MAX as f64) as u64;
    let mut next = gap(&mut rng);
    for b in ram.iter_mut() {
        while next < 8 {
            *b ^= 1 << next;
            next += 1 + gap(&mut rng);
        }
        next -= 8;
    }
    ram
}

