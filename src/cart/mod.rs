//! Cartridges: CRT file parsing and banking of the supported types.
//!
//! The C64 sees a cartridge through the /EXROM and /GAME lines, which the PLA
//! combines with LORAM/HIRAM/CHAREN (see `Bus::map_read`), and through the
//! two I/O areas $DE00-$DEFF (I/O1) and $DF00-$DFFF (I/O2), where the
//! banking registers live:
//!
//! | /EXROM | /GAME | mode    | visible ROMs                                   |
//! |--------|-------|---------|------------------------------------------------|
//! | high   | high  | off     | none                                           |
//! | low    | high  | 8K      | ROML at $8000-$9FFF                            |
//! | low    | low   | 16K     | ROML at $8000, ROMH at $A000-$BFFF             |
//! | high   | low   | Ultimax | ROML at $8000, ROMH at $E000-$FFFF, only 4K of RAM |
//!
//! ROMs are kept in 8K banks, ROML and ROMH separately; a missing bank reads
//! $FF (erased flash or missing EPROM). A chip smaller than 8K repeats
//! within its window, as on the bus (high address lines not connected).
//!
//! EasyFlash, GMod2 and Megabyter have writable flash (see `flash.rs`): the
//! commands arrive with CPU writes in Ultimax mode, at $8000-$9FFF for the
//! ROML chip and at $E000-$FFFF for the ROMH one (the GMod2 enables Ultimax
//! only on writes and programs through the high window).
//!
//! The behaviour of each type follows the CRT documentation and VICE, which
//! it is compared against by the tests in tests/vice_mem.rs (test cartridges
//! generated by tools/vice_tests.py).

mod eeprom;
mod flash;

use eeprom::M93c86;
use flash::{Chip, Flash};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Mode {
    Off,
    Game8K,
    Game16K,
    Ultimax,
}

impl Mode {
    /// From the /EXROM and /GAME lines (true = low, active).
    fn from_lines(exrom_low: bool, game_low: bool) -> Self {
        match (exrom_low, game_low) {
            (false, false) => Mode::Off,
            (true, false) => Mode::Game8K,
            (true, true) => Mode::Game16K,
            (false, true) => Mode::Ultimax,
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Mode::Off => "off",
            Mode::Game8K => "8K",
            Mode::Game16K => "16K",
            Mode::Ultimax => "Ultimax",
        }
    }
}

/// Supported cartridge types, with their CRT format number.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Kind {
    /// 0: fixed ROMs, 8K, 16K or Ultimax according to the lines in the header.
    Normal,
    /// 5: 8K banks selected with $DE00 (bits 0-5). Up to 256K in 16K mode
    /// with the same bank also at $A000; the 512K one (Terminator 2) in 8K mode.
    Ocean,
    /// 7: Fun Play / Power Play: 16 banks, $DE00 = bank bits 5-3 and 0;
    /// $86 disables the ROM.
    FunPlay,
    /// 8: 4 16K banks; $DF00: bits 0-1 bank, bit 2 disables, bit 3 locks
    /// the register until reset.
    SuperGames,
    /// 15: C64 Game System / System 3: 64 banks, any access to
    /// $DE00-$DEFF selects the bank with the low 6 bits of the address.
    Gs,
    /// 17: 16 banks, selected by reading $DE00-$DE0F.
    Dinamic,
    /// 18: Zaxxon / Super Zaxxon: 4K at $8000 mirrored at $9000; a read at
    /// $8000-$8FFF maps bank 0 at $A000, at $9000-$9FFF bank 1.
    Zaxxon,
    /// 19: Magic Desk / Domark / HES Australia: $DE00 bits 0-6 bank, bit 7
    /// disables the ROM.
    MagicDesk,
    /// 23: 16K or 32K in 16K mode; reading $DE00 switches to bank 1, reading
    /// $DF00 disables the cartridge.
    Ross,
    /// 32: EasyFlash: $DE00 bank (0-63), $DE02 mode, 256 bytes of RAM at $DF00.
    EasyFlash,
    /// 57: RGCD (and Hucky, revision 1 with banks in reverse order):
    /// $DE00 bits 0-2 bank, bit 3 disables until reset.
    Rgcd,
    /// 60: GMod2: 512K flash, $DE00 bits 0-5 bank, bit 6 disables the ROM and
    /// selects the serial EEPROM (bit 5 clock, bit 4 data), read at bit 7.
    GMod2,
    /// 74: Drean (Argentinian H.E.R.O.): $DF00 bits 0-1 bank, bit 5 disables.
    Drean,
    /// 85: Magic Desk 16K: like Magic Desk but with 16K banks.
    MagicDesk16,
    /// 86: Megabyter: 1M flash, $DE00 bank (0-127), $DE02 mode.
    Megabyter,
    /// 87: Magic Desk Plus: Magic Desk with 128K SRAM and/or parallel EEPROM
    /// in a 256-byte window at $DF00 ($DE01 page, $DE03 control).
    MagicDeskPlus,
}

impl Kind {
    fn from_crt(t: u16) -> Option<Kind> {
        Some(match t {
            0 => Kind::Normal,
            5 => Kind::Ocean,
            7 => Kind::FunPlay,
            8 => Kind::SuperGames,
            15 => Kind::Gs,
            17 => Kind::Dinamic,
            18 => Kind::Zaxxon,
            19 => Kind::MagicDesk,
            23 => Kind::Ross,
            32 => Kind::EasyFlash,
            57 => Kind::Rgcd,
            60 => Kind::GMod2,
            74 => Kind::Drean,
            85 => Kind::MagicDesk16,
            86 => Kind::Megabyter,
            87 => Kind::MagicDeskPlus,
            _ => return None,
        })
    }

    pub fn crt_type(self) -> u16 {
        match self {
            Kind::Normal => 0,
            Kind::Ocean => 5,
            Kind::FunPlay => 7,
            Kind::SuperGames => 8,
            Kind::Gs => 15,
            Kind::Dinamic => 17,
            Kind::Zaxxon => 18,
            Kind::MagicDesk => 19,
            Kind::Ross => 23,
            Kind::EasyFlash => 32,
            Kind::Rgcd => 57,
            Kind::GMod2 => 60,
            Kind::Drean => 74,
            Kind::MagicDesk16 => 85,
            Kind::Megabyter => 86,
            Kind::MagicDeskPlus => 87,
        }
    }

    pub fn name(self) -> &'static str {
        crt_type_name(self.crt_type())
    }

    /// Types with flash: all banks exist, those missing from the CRT are
    /// erased ($FF) and the register does not wrap around the present banks.
    fn flash(self) -> bool {
        matches!(self, Kind::EasyFlash | Kind::GMod2 | Kind::Megabyter)
    }

    /// Types in which every chip goes into the ROML banks by its bank
    /// number, whatever the load address in the CRT.
    fn roml_only(self) -> bool {
        matches!(self, Kind::Ocean | Kind::FunPlay | Kind::Gs | Kind::Dinamic | Kind::MagicDesk
            | Kind::Rgcd | Kind::GMod2 | Kind::Drean | Kind::Megabyter | Kind::MagicDeskPlus)
    }

    /// Bank bits of the register.
    fn register_mask(self) -> u8 {
        match self {
            Kind::Normal => 0,
            Kind::SuperGames | Kind::Drean => 0x03,
            Kind::Rgcd => 0x07,
            Kind::FunPlay | Kind::Dinamic => 0x0F,
            Kind::Zaxxon | Kind::Ross => 0x01,
            Kind::Ocean | Kind::Gs | Kind::EasyFlash | Kind::GMod2 => 0x3F,
            Kind::MagicDesk | Kind::MagicDesk16 | Kind::Megabyter | Kind::MagicDeskPlus => 0x7F,
        }
    }
}

