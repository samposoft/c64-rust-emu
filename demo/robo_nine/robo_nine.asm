; --- program ----------------------------------------------------------------
        * = $0801
        .word (+), 2026
        .null $9e, format("%d", start)
+       .word 0

start   sei
        cld
        ldx #2                  ; keep BASIC's zero page for the way back
-       lda $00,x
        sta zpsave,x
        inx
        bne -
        ldx #$ff
        txs
        lda #$7f                ; no CIA interrupts
        sta $dc0d
        sta $dd0d
        lda $dc0d
        lda $dd0d
        lda #$33                ; character ROM visible: copy chars 0-63
        sta $01
        ldx #0
-       lda $d000,x
        sta CHARSET,x
        lda $d100,x
        sta CHARSET+$100,x
        inx
        bne -
        lda #$35                ; RAM + I/O, no ROMs
        sta $01
        lda #<nmi
        sta $fffa
        lda #>nmi
        sta $fffb

        ldx #0                  ; robot characters
-       lda robchars,x
        sta CHARSET+CHAR0*8,x
        lda robchars+$100,x
        sta CHARSET+CHAR0*8+$100,x
        lda robchars+$200,x
        sta CHARSET+CHAR0*8+$200,x
        inx
        bne -
        ldx #0                  ; sprites: empty + 9 digits
-       lda sprites,x
        sta SPRMEM,x
        lda sprites+$100,x
        sta SPRMEM+$100,x
        lda sprites+$200,x
        sta SPRMEM+$200,x
        inx
        bne -
        lda #$ff                ; idle byte: all black
        sta $3fff

        ldx #0                  ; clear screen and colours
-       lda #$20
        sta SCREEN,x
        sta SCREEN+$100,x
        sta SCREEN+$200,x
        sta SCREEN+$2e8,x
        lda #BG
        sta $d800,x
        sta $d900,x
        sta $da00,x
        sta $dae8,x
        inx
        bne -

        ldx #$2e                ; VIC
-       lda vicinit,x
        sta $d000,x
        dex
        bpl -
        lda #$1c                ; screen $0400, characters $3000
        sta $d018

        ldx #zpend-frame-1      ; variables
        lda #0
-       sta frame,x
        dex
        bpl -
        lda #$ff
        sta look
        lda #$08                ; text mode until the robot appears
        sta d016v
        lda #<txt_presents      ; bar 0: title
        ldx #>txt_presents
        jsr print
        ldx #8
-       lda #M_HIDE
        sta omode,x
        dex
        bpl -
        ldx #$18                ; SID
        lda #0
-       sta $d400,x
        dex
        bpl -
        jsr init
        .if SKIP                ; testing: start with the row in the border
        jsr draw_robot
        lda #$18
        sta d016v
        lda #1
        sta eyeson
        lda #SKIP
        sta bar
        lda #95
        sta fib
        ldx #8
-       lda #M_SLOT
        sta omode,x
        dex
        bpl -
        .endif

        jsr sync_timer

        lda #<irq_bot
        sta $fffe
        lda #>irq_bot
        sta $ffff
        lda #249
        sta $d012
        lda #$1b
        sta $d011
        lda #1
        sta $d01a
        sta $d019
        cli

; main loop: after the bottom interrupt prepares the next frame
mainlp  lda frame
-       cmp frame
        beq -
        jsr step
        jmp mainlp

nmi     rti

; --- start CIA1 timer A in step with the raster ------------------------------
; A double interrupt gives a stable raster position; the timer then runs
; forever with a period of one line, so its value tells the raster cycle.
sync_timer
        lda #62
        sta $dc04
        lda #0
        sta $dc05
        lda #<irq_s1
        sta $fffe
        lda #>irq_s1
        sta $ffff
        lda #100
        sta $d012
        lda #$1b
        sta $d011
        lda #1
        sta $d01a
        sta $d019
        lda #0
        sta cnt
        cli
-       lda cnt
        beq -
        sei
        rts

irq_s1  lda #<irq_s2
        sta $fffe
        lda #>irq_s2
        sta $ffff
        inc $d012
        asl $d019
        tsx
        cli
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
irq_s2  txs                     ; 0 or 1 cycle of jitter here
        ldx #8
-       dex
        bne -
        bit $00
        lda $d012
        cmp $d012
        beq +                   ; one more cycle if the line has not changed
+       .fill SYNCNOP, $ea      ; tuning: puts the timer in phase
        .if SYNCBIT
        bit $ea
        .endif
        lda #$11                ; force load, start, continuous
        sta $dc0e
        asl $d019
        inc cnt
        rti

; --- interrupts -------------------------------------------------------------
; line 249: open the lower (and so the upper) border, set up the sprites of
; the next frame, play the music, choose the next interrupt
irq_bot sta bra+1
        stx brx+1
        sty bry+1
        lda #$13                ; 24 rows: the border does not start at line 251
        sta $d011
        lda #0                  ; no sprites in the lower border: a Y below 56
        sta $d015               ; would show them again 256 lines later
        lda #1
        sta $d019
        lda ready
        bne +
        jmp noupd
+
        ldx #7
-       lda n_c,x
        sta $d027,x
        lda n_p,x
        sta SCREEN+$3f8,x
        dex
        bpl -
        .for i = 0, i < 8, i += 1
        lda n_x+i
        sta $d000+2*i
        lda n_y+i
        sta $d001+2*i
        .next
        lda n_msb
        sta $d010
        lda n_en
        sta spr_en
        ldx #n_end-n_band-1
-       lda n_band,x
        sta band_on,x
        dex
        bpl -
        lda #0
        sta ready
noupd
-       lda $d011               ; back to 25 rows after line 251
        bmi +
        lda $d012
        cmp #252
        bcc -
+       lda #$1b
        sta $d011
        lda d016v
        sta $d016
        jsr play
        inc frame
        lda #<irq_top
        ldx #>irq_top
        ldy #5
        jmp setirq

; line 5: sprites on, then the next interrupt of the frame
irq_top sta bra+1
        stx brx+1
        sty bry+1
        lda spr_en
        sta $d015
        lda #1
        sta $d019
        jmp nextirq

; line 22 below the top sprite: reuse sprite 0 for the ninth object
irq_mux sta bra+1
        stx brx+1
        sty bry+1
        lda mux_y
        sta $d001
        lda mux_x
        sta $d000
        lda $d010
        and #$fe
        ora mux_xh
        sta $d010
        lda mux_c
        sta $d027
        lda mux_p
        sta SCREEN+$3f8
        lda #1
        sta $d019
        lda #<irq_bot
        ldx #>irq_bot
        ldy #249
        jmp setirq

; next interrupt after the bottom one: ghost band, sprite reuse or bottom
nextirq lda band_on
        beq +
        lda #<irq_band
        ldx #>irq_band
        ldy band_line
        jmp setirq
+       lda mux_on
        beq +
        lda #<irq_mux
        ldx #>irq_mux
        ldy mux_line
        jmp setirq
+       lda #<irq_bot
        ldx #>irq_bot
        ldy #249
setirq  sta $fffe
        stx $ffff
        sty $d012
bra     lda #0
brx     ldx #0
bry     ldy #0
        rti

; the line before the ghost digit: draw it, one raster line per block.
; Each block waits until the timer says cycle 11-19 (the sprite DMA of the
; line is over by then), then waits 10-2 more cycles to land on cycle 35:
;   cycle 40: $3FFF = glyph row    (fetched at 41 = column 26)
;   cycle 44: $D021 = black        (the digit's colour covered 8+2 pixels)
;   cycle 48: $3FFF = $FF, cycle 55: $D021 = digit colour for the next line
; A write at cycle 55 is still allowed when the sprite DMA starts, so after
; it the CPU only has the next block's timer read to do.
irq_band
        sta bra+1
        stx brx+1
        sty bry+1
        lda #0                  ; the scroll change leaves a few background
        sta $d021               ; pixels: black
        lda #XS                 ; hires (the idle byte must not be multicolour),
        sta $d016               ; 38 columns (covers the pixels left by the scroll)
        lda band_col
        sta $d021
        ldx #$ff                ; all black
        ldy #0                  ; black
        .for i = 0, i < BANDH, i += 1
        .block
        .if (* & $ff) > $100 - 8 || ((* + 12) & $ff) > $100 - 2 - 20
        jmp +                   ; the branches must not cross a page
        .align $100
+
        .endif
wait    lda $dc04
        cmp #TH+1
        bcs wait
        eor #$1f                ; 31 - timer: skip more when later
        sta br+1
br      bpl *+2
        .fill FILL, $ea         ; never executed
        .byte $c9, $c9, $c9, $c9, $c9, $c9, $c9, $c5, $ea
        lda #GPAT[i]
        sta $3fff               ; glyph row
        sty $d021               ; black
        stx $3fff               ; all black again
        lda band_col
        sta $d021               ; digit colour
        .bend
        .next
        sty $d021               ; black while the scroll changes back
        lda d016v
        sta $d016
        lda #BG
        sta $d021
        lda #1
        sta $d019
        lda #<irq_bot
        ldx #>irq_bot
        ldy #249
        jmp setirq

; --- one frame of the show (main loop) ----------------------------------------
step    jsr clock
        jsr script
        jsr fade
        jsr robot
        jsr places
        jsr sprites_out
        rts

clock   inc fib
        lda fib
        cmp #96
        bcc +
        lda #0
        sta fib
        inc bar
+       lda theta               ; the orbit turns 2 units per frame
        clc
        adc #$00
        sta theta
        lda theta+1
        adc #2
        sta theta+1
        lda wave
        beq +
        inc wphase
+       rts

; events of the show, on the first frame of a bar and in the middle of it
script  lda fib
        beq onbar
        cmp #48
        beq onhalf
        rts

onhalf  lda bar
        cmp #2                  ; bar 2.5: the robot wakes up
        bne +
        lda #1
        sta eyeson
        rts
+       cmp #46                 ; bars 46.5-49.5: digits 2, 4, 6, 8 go home
        bcc +
        cmp #50
        bcs +
        sbc #46-1               ; carry clear: A - 46
        asl a
        ora #1
        tax
        jmp absorb
+       rts

onbar   lda bar
        cmp #2                  ; bar 2: the robot
        bne +
        lda #12
        jsr clearrow
        jsr draw_robot
        lda #$18
        sta d016v
        rts
+       cmp #3                  ; bars 3-11: digits 1-9 come out
        bcc +
        cmp #12
        bcs +
        sbc #3-1                ; carry clear: A - 3
        tax
        lda #24
        sta hatch
        lda #K_CHEST
        ldy #K_ORBIT
        jmp startlerp
+       cmp #16                 ; bars 16-24: digits 1-9 fly to the row
        bcc +
        cmp #25
        bcs +
        sbc #16-1
        tax
        lda #K_ORBIT
        ldy #K_SLOT
        jmp startlerp
+       cmp #25                 ; bar 25: the wave and the captions
        bne +
        lda #1
        sta wave
        lda #0
        sta wphase
        lda #<txt_nine
        ldx #>txt_nine
        jsr print
        lda #<txt_eight
        ldx #>txt_eight
        jmp print
+       cmp #33                 ; bar 33: the wave stops
        bne +
        lda #0
        sta wave
        lda #21
        jsr clearrow
        lda #23
        jsr clearrow
        lda bar
+       cmp #33                 ; bars 33-41: back to the orbit, 9 first
        bcc +
        cmp #42
        bcs +
        eor #$ff                ; 41 - bar
        sec
        adc #41
        tax
        lda #K_SLOT
        ldy #K_ORBIT
        jmp startlerp
+       cmp #46                 ; bars 46-50: digits 1, 3, 5, 7, 9 go home
        bcc +
        cmp #51
        bcs +
        sbc #46-1
        asl a
        tax
        jmp absorb
+       cmp #51                 ; bar 51: the robot switches off
        bne +
        lda #0
        sta eyeson
        rts
+       cmp #52                 ; bar 52: back to BASIC
        bne +
        jmp tobasic
+       rts

; bar 51: the music fades out (volume 15 to 0 in 96 frames)
fade    lda bar
        cmp #51
        bne ++
        ldx #15
        lda fib
-       sec
        sbc #6
        bcc +
        dex
        bne -
+       txa
        ora #$10                ; low-pass filter, as the player sets it
        sta $d418
+       rts

; the end: machine as at power-on, program still in memory, READY.
tobasic sei
        lda #0
        sta $d01a               ; no raster interrupts
        sta $d015
        lda #$ff
        sta $d019
        ldx #$18                ; SID silent
        lda #0
-       sta $d400,x
        dex
        bpl -
        ldx #2                  ; BASIC's zero page back
-       lda zpsave,x
        sta $00,x
        inx
        bne -
        lda #$37                ; BASIC and KERNAL ROMs
        sta $01
        jsr $fda3               ; IOINIT: CIAs, KERNAL timer interrupt
        jsr $ff81               ; CINT: VIC and screen editor, clears the screen
        jmp ($a002)             ; BASIC warm start: READY.

absorb  lda #K_ORBIT
        ldy #K_CHEST
        jsr startlerp
        lda #24
        sta hatch
        rts

; object X: lerp from place A to place Y
startlerp
        sta oa,x
        tya
        sta ob,x
        lda #M_LERP
        sta omode,x
        lda #0
        sta ot,x
        stx look
        rts

; --- robot ------------------------------------------------------------------
ROBS    = SCREEN + ROBOT_ROW * 40 + ROBOT_COL
ROBC    = $d800 + ROBOT_ROW * 40 + ROBOT_COL

draw_robot
        lda #<ROBS
        sta ptr
        lda #>ROBS
        sta ptr+1
        ldx #0
drrow   ldy #0
-       lda robscr,x
        sta (ptr),y
        lda ptr+1               ; colour RAM: same offset from $D800
        pha
        clc
        adc #>($d800-SCREEN)
        sta ptr+1
        lda robcol,x
        sta (ptr),y
        pla
        sta ptr+1
        inx
        iny
        cpy #6
        bne -
        lda ptr
        clc
        adc #40
        sta ptr
        bcc +
        inc ptr+1
+       cpx #60
        bne drrow
        rts

; per frame: eyes (off, looking, blinking), hatch, antenna bulb, chest lights
robot   lda bar
        cmp #2
        bcs +
        rts
+       lda beat                ; drums from the player
        beq nobeat
        cmp #2
        bne +
        lda #6                  ; snare: bulb yellow
        sta bulb
+       inc lights
        lda #0
        sta beat
nobeat  lda #8|2                ; antenna bulb
        ldx bulb
        beq +
        dec bulb
        lda #8|7
+       sta ROBC+2
        sta ROBC+3
        lda #8|0                ; hatch: lit while a digit comes or goes
        ldx hatch
        beq +
        dec hatch
        lda #8|7
+       sta ROBC+5*40+2
        sta ROBC+5*40+3
        lda lights              ; chest lights rotate on every drum
        and #3
        tax
        ldy #0
-       lda lightcol,x
        sta ROBC+6*40+1,y
        inx
        iny
        cpy #4
        bne -
        lda eyeson              ; eyes: off until bar 2.5, then cyan
        beq eyesoff
        inc blink
        ldx #3
        lda blink
        cmp #6
        bcc eyeset
        cmp #150
        bcc +
        lda #0
        sta blink
+       ldx #0                  ; look at the moving digit
        ldy look
        bmi eyeset
        lda omode,y
        cmp #M_LERP
        beq +
        lda #$ff
        sta look
        bne eyeset
+       lda oxh,y
        bne lookr
        lda oxl,y
        cmp #150
        bcc lookl
        cmp #212
        bcc eyeset
lookr   ldx #2
        bne eyeset
lookl   ldx #1
eyeset  lda eyel,x
        sta ROBS+2*40+1
        lda eyer,x
        sta ROBS+2*40+4
        lda #8|3
        bne +
eyesoff lda #8|0
+       sta ROBC+2*40+1
        sta ROBC+2*40+4
        rts

lightcol .byte 8|2, 8|7, 8|5, 8|3, 8|2, 8|7, 8|5

; --- places of the digits ---------------------------------------------------
places  ldx #8
-       stx cnt
        jsr place1
        ldx cnt
        dex
        bpl -
        rts

place1  lda omode,x
        cmp #M_LERP
        beq plerp
        cmp #M_HIDE
        beq +
where1  jsr where               ; orbit or slot (= place kind): straight there
        ldx cnt
        lda px
        sta oxl,x
        lda px+1
        sta oxh,x
        lda py
        sta oy,x
+       rts

plerp   lda ot,x                ; last step: exactly at B
        cmp #64
        bcc +
        lda ob,x
        tay
        lda endmode,y
        sta omode,x
        tya
        jmp where1
+       lda oa,x                ; A
        jsr where
        lda px
        sta ax
        lda px+1
        sta ax+1
        lda py
        sta ay
        ldx cnt
        lda ob,x                ; B
        jsr where
        ldx cnt
        ldy ot,x
        lda ease,y
        sta fac2
        lda px                  ; x = A + (B - A) * e
        sec
        sbc ax
        sta dl
        lda px+1
        sbc ax+1
        sta dl+1
        jsr lerp
        lda dl
        clc
        adc ax
        sta oxl,x
        lda dl+1
        adc ax+1
        sta oxh,x
        lda py                  ; y
        sec
        sbc ay
        sta dl
        lda #0
        sbc #0
        sta dl+1
        jsr lerp
        lda dl
        clc
        adc ay
        sta oy,x
        inc ot,x
        rts

endmode .byte M_HIDE, M_ORBIT, M_SLOT

; place of kind A for object cnt -> px, py
where   ldx cnt
        cmp #K_ORBIT
        beq wo
        cmp #K_SLOT
        beq ws
        lda #<CHESTX            ; chest
        sta px
        lda #>CHESTX
        sta px+1
        lda #CHESTY
        sta py
        rts
wo      lda theta+1
        clc
        adc slotang,x
        tay
        lda orbxl,y
        sta px
        lda orbxh,y
        sta px+1
        lda orby,y
        sta py
        rts
ws      lda slotxl,x
        sta px
        lda slotxh,x
        sta px+1
        lda #ROWY
        ldy wave
        beq +
        txa                     ; wave: each digit 4 frames after the previous
        asl a
        asl a
        eor #$ff
        sec
        adc wphase
        and #63
        tay
        lda #ROWY
        sec
        sbc hop,y
+       sta py
        rts

; dl = dl * fac2 / 256, dl signed (-511..511), fac2 0-255. Keeps X.
lerp    lda dl+1
        sta neg
        bpl +
        lda #0
        sec
        sbc dl
        sta dl
        lda #0
        sbc dl+1
        sta dl+1
+       lda dl
        sta fac1
        lda #0                  ; fac1 * fac2 -> A:fac1
        ldy #8
        lsr fac1
-       bcc +
        clc
        adc fac2
+       ror a
        ror fac1
        dey
        bne -
