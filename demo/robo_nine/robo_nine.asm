; --- sprites of the next frame ------------------------------------------------
; Objects that are not hidden (and the ghost digit when it sits in its slot)
; are sorted by Y; eight go to the sprites, a ninth reuses sprite 0 below
; the first one.
sprites_out
        lda ready               ; the interrupt has not taken the last ones
        beq +
        rts
+
        ldx #0
        ldy #0
        sty n_band
-       lda omode,x
        beq next
        cpx #GI
        bne +
        cmp #M_SLOT
        bne +
        lda #1                  ; ghost digit in its slot: not a sprite
        sta n_band
        lda oy,x
        clc
        adc #BANDOFF
        sta n_bline
        lda digcol,x
        sta n_bcol
        jmp next
+       txa
        sta order,y
        lda oy,x
        sta keys,y
        iny
next    inx
        cpx #9
        bne -
        sty nobj
        ; insertion sort by Y
        ldx #1
s_outer cpx nobj
        bcs sorted
        lda order,x
        sta sid
        lda keys,x
        sta skey
        txa
        tay
s_in    lda keys-1,y
        cmp skey
        bcc s_put
        beq s_put
        sta keys,y
        lda order-1,y
        sta order,y
        dey
        bne s_in
s_put   lda skey
        sta keys,y
        lda sid
        sta order,y
        inx
        jmp s_outer
sorted  lda #0
        sta n_msb
        sta n_mux
        ldx #0                  ; x = sprite
-       cpx nobj
        bcs spoff
        cpx #8
        bcs spoff
        ldy order,x
        lda oxl,y
        sta n_x,x
        lda oxh,y
        beq +
        lda bitval,x
        ora n_msb
        sta n_msb
+       lda oy,y
        sta n_y,x
        lda digcol,y
        sta n_c,x
        tya
        clc
        adc #SPRBLK+1
        sta n_p,x
        inx
        bne -
spoff   lda enmask,x
        sta n_en
        lda nobj                ; a ninth sprite object: reuse sprite 0
        cmp #9
        bcc sprok
        ldy order
        lda oy,y
        clc
        adc #22
        sta n_mline
        ldy order+8
        lda oy,y
        sec
        sbc n_mline
        bcc sprok               ; too close: the ninth waits (never here)
        cmp #3
        bcc sprok
        lda #1
        sta n_mux
        lda oy,y
        sta n_my
        lda oxl,y
        sta n_mx
        lda oxh,y
        sta n_mxh
        lda digcol,y
        sta n_mc
        tya
        clc
        adc #SPRBLK+1
        sta n_mp
sprok   lda #1
        sta ready
sprdone rts

