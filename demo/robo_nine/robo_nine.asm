; ROBO NINE - a Commodore 64 intro for 64tass (without -a)
;
; A robot pulls nine digits out of its chest, they circle around it, then
; they line up in the top border: nine digits on the same raster lines,
; although the VIC-II has only eight sprites. Inspired by "Nine" by Linus
; Akesson (lft, 2025); the code and the trick used here are our own.
;
; The ninth digit is not a sprite. In the open border the VIC shows the idle
; byte ($3FFF in bank 0) with black pixels over the background colour. Every
; raster line of the digit writes the inverted glyph row into $3FFF, then
; 4 cycles later sets $D021 back to black: the only 8 pixels fetched with the
; new byte while the background still had the digit's colour are the digit.
; The writes must land on exact cycles although the sprite DMA of every line
; changes as the other digits fly in; a CIA timer that runs in step with the
; raster (63 cycles) tells each line how many cycles to wait.
;
; Data (sprites, robot, tables, music) are generated by gen_data.py.

zp      = $fb           ; player: pointer (2 bytes)
tmp     = $fd
tmp2    = $fe
tmp3    = $02

; --- constants --------------------------------------------------------------
BG      = 6             ; background: blue
XS      = 7             ; fine scroll during the ghost band
GHOSTC  = 26            ; text column of the idle byte with the ghost digit
GHOSTX  = 24 + 8 * GHOSTC + XS + 2   ; its sprite X (the glyph is in bits 5-0)
SLOTDX  = 24            ; distance between the digits of the row
ROWY    = 30            ; sprite Y of the row in the top border
TH      = 20            ; timer value at cycle 11 of a line (see sync_timer)
FILL    = 31 - TH       ; bytes skipped by the smallest wait
BANDH   = 16            ; lines of the ghost digit
GI      = GHOST - 1     ; object index of the ghost digit
SPRBLK  = $e0           ; sprite block of the empty sprite ($3800)
SYNCNOP = 9             ; NOPs before the timer starts (sets its phase)
SYNCBIT = 1             ; and one more 3-cycle instruction
SKIP    = 0             ; testing: first bar of the show (0 = from the start)
BANDOFF = 0             ; raster line of the band interrupt minus sprite Y

SCREEN  = $0400
CHARSET = $3000
SPRMEM  = $3800

; objects (the nine digits): modes and places
M_HIDE  = 0
M_ORBIT = 1
M_SLOT  = 2
M_LERP  = 3
K_CHEST = 0
K_ORBIT = 1
K_SLOT  = 2

